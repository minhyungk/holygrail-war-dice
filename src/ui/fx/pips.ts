// 주사위 눈 자리 (면 0~1 좌표). 3D 다이스와 합산 칩이 같이 쓴다. 6은 두 줄 세 개씩
const PIPS: Record<number, [number, number][]> = {
  1: [[0.5, 0.5]],
  2: [[0.28, 0.28], [0.72, 0.72]],
  3: [[0.27, 0.27], [0.5, 0.5], [0.73, 0.73]],
  4: [[0.28, 0.28], [0.72, 0.28], [0.28, 0.72], [0.72, 0.72]],
  5: [[0.27, 0.27], [0.73, 0.27], [0.5, 0.5], [0.27, 0.73], [0.73, 0.73]],
  6: [[0.28, 0.25], [0.28, 0.5], [0.28, 0.75], [0.72, 0.25], [0.72, 0.5], [0.72, 0.75]],
};
export const pipLayout = (n: number) => PIPS[n] ?? [];
/** 눈 반지름 (면 한 변 대비). 1의 눈은 크게 */
export const pipRadius = (n: number) => (n === 1 ? 0.13 : 0.085);
