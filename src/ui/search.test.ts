// 촉매 소환 검색 (D-157)
import { describe, expect, it } from 'vitest';
import { matchScore } from './search';

describe('서번트 이름 검색', () => {
  it.each([
    ['알트리아 펜드래곤', '알트', 3],
    ['알트리아 펜드래곤', '앑', 3], // "알트"를 치는 중 (ㄹ+ㅌ 겹받침)
    ['알트리아 펜드래곤', '아', 3],
    ['알트리아 펜드래곤', 'ㅇㅌㄹㅇ', 3], // 초성
    ['가웨인', '가', 3],
    ['각성', '가', 3], // 받침 없는 마지막 글자는 같은 초성·중성의 글자 전부
    ['길가메시', '가', 2], // 중간 일치는 점수가 낮다
    ['쿠 훌린', '훌린', 2],
    ['쿠 훌린', '쿠훌', 3], // 공백 무시
    ['메두사', '메데', 0],
    ['BB', 'bb', 3],
    ['잔 다르크(얼터)', '잔다르크얼', 3],
    ['헤라클레스', '헬', 3], // "헤라"를 치는 중
    ['헤라클레스', '헴', 0],
    ['아무 이름', '', 1],
  ] as const)('%s ← "%s" = %i', (name, q, score) => expect(matchScore(name, q)).toBe(score));
});
